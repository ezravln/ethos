.global idt_load
.type idt_load, @function
idt_load:
	lidt (%rdi)
	ret
.size idt_load, . - idt_load

.macro ISR_NOERR number
.global ethos_isr\number
.type ethos_isr\number, @function
ethos_isr\number:
	pushq $0
	pushq $\number
	jmp idt_common_entry
.size ethos_isr\number, . - ethos_isr\number
.endm

.macro ISR_ERR number
.global ethos_isr\number
.type ethos_isr\number, @function
ethos_isr\number:
	pushq $\number
	jmp idt_common_entry
.size ethos_isr\number, . - ethos_isr\number
.endm

.macro IRQ_STUB number
.global ethos_irq\number
.type ethos_irq\number, @function
ethos_irq\number:
	pushq $0
	pushq $(32 + \number)
	jmp idt_irq_common_entry
.size ethos_irq\number, . - ethos_irq\number
.endm

